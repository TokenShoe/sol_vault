/**
 * Build the rebalance_cctp instruction. messageSentEventData is a freshly generated Keypair and must co-sign.
 * No recipient argument: the program reads it from the CctpRoute registered by admin (setCctpRoute).
 */
export async function rebalanceCctpIx(
  program: Program<CrossVault>,
  rebalancer: PublicKey,
  mint: PublicKey,
  amount: bigint | number,
  destinationDomain: number,
  messageSentEventData: PublicKey
): Promise<TransactionInstruction> {
  return program.methods
    .rebalanceCctp(bn(amount), destinationDomain)
    .accountsPartial({
      rebalancer,
      mint,
      pool: poolPda(mint),
      vault: vaultAddress(mint),
      route: cctpRoutePda(destinationDomain),
      messageSentEventData,
      tokenProgram: TOKEN_PROGRAM_ID,
      ...cctpAccounts(mint, destinationDomain),
    })
    .instruction();
}

/** Start a CCTP rebalance; returns the tx signature and message account (needed later for the attestation and rent reclaim) */
export async function rebalanceCctp(
  program: Program<CrossVault>,
  rebalancer: Keypair,
  mint: PublicKey,
  amount: bigint | number,
  destinationDomain: number
): Promise<{ signature: string; messageSentEventData: PublicKey }> {
  const eventKp = Keypair.generate();
  const ix = await rebalanceCctpIx(program, rebalancer.publicKey, mint, amount, destinationDomain, eventKp.publicKey);
  const tx = new Transaction().add(ComputeBudgetProgram.setComputeUnitLimit({ units: 250_000 }), ix);
  const signature = await sendAndConfirmTransaction(program.provider.connection, tx, [rebalancer, eventKp], { commitment: "confirmed" });
  return { signature, messageSentEventData: eventKp.publicKey };
}

/** Cross-chain message status returned by Circle Iris */
export interface CctpMessageStatus {
  status: string; // pending_confirmations / complete
  message: string | null; // 0x..., only present once complete
  attestation: string | null; // 0x..., only present once complete ("PENDING" while pending)
  eventNonce?: string;
  raw: any;
}

/**
 * Query the attestation of a CCTP transaction on Solana (standard mode waits for source-chain finality)
 * Once complete, call MessageTransmitterV2.receiveMessage(message, attestation) on the destination chain to finish the transfer
 * @param fetchImpl optional fetch implementation (e.g. one that goes through a proxy)
 */
export async function fetchCctpAttestation(
  txSignature: string,
  opts: { testnet?: boolean; fetchImpl?: typeof fetch } = {}
): Promise<CctpMessageStatus | null> {
  const base = opts.testnet === false ? CCTP.IRIS.MAINNET : CCTP.IRIS.TESTNET;
  const f = opts.fetchImpl ?? fetch;
  const res = await f(`${base}/v2/messages/${CCTP.SOLANA_DOMAIN}?transactionHash=${txSignature}`);
  if (res.status === 404) return null; // Circle has not indexed this transaction yet
  const j: any = await res.json();
  const m = j?.messages?.[0];
  if (!m) return null;
  return {
    status: m.status,
    message: m.message ?? null,
    attestation: m.attestation && m.attestation !== "PENDING" ? m.attestation : null,
    eventNonce: m.eventNonce,
    raw: m,
  };
}

/**
 * Build the CCTP MessageTransmitterV2.reclaim_event_account instruction: closes the message account and refunds its rent (~0.0039 SOL) to payee
 * @param payee        the account that paid the rent (= rebalancer), must sign
 * @param eventAccount message account address (RebalanceCctpEvent.message_sent_event_data)
 * @param attestation  Circle attestation (0x-prefixed hex)
 * @param message      cross-chain message (0x-prefixed hex)
 */
export function reclaimCctpEventAccountIx(
  payee: PublicKey,
  eventAccount: PublicKey,
  attestation: string,
  message: string
): TransactionInstruction {
  const att = Buffer.from(attestation.replace(/^0x/, ""), "hex");
  const msg = Buffer.from(message.replace(/^0x/, ""), "hex");
  const u32 = (n: number) => {
    const b = Buffer.alloc(4);
    b.writeUInt32LE(n);
    return b;
  };
  // discriminator (from the official CCTP IDL) + ReclaimEventAccountParams { attestation: bytes, destination_message: bytes }
  const data = Buffer.concat([Buffer.from([94, 198, 180, 159, 131, 236, 15, 174]), u32(att.length), att, u32(msg.length), msg]);
  return new TransactionInstruction({
    programId: CCTP.MESSAGE_TRANSMITTER_V2,
    keys: [
      { pubkey: payee, isSigner: true, isWritable: true },
      { pubkey: cctpPda(["message_transmitter"], CCTP.MESSAGE_TRANSMITTER_V2), isSigner: false, isWritable: true },
      { pubkey: eventAccount, isSigner: false, isWritable: true },
    ],
    data,
  });
}

/** Rent reclaim result */
export type ReclaimResult =
  | { status: "reclaimed"; signature: string; lamports: number } // reclaimed
  | { status: "already_closed" } // account no longer exists (reclaimed earlier)
  | { status: "attestation_pending"; cctpStatus: string | null } // Circle attestation not ready yet
  | { status: "window_not_expired" }; // CCTP reclaim window not reached yet, retry later

/**
 * Reclaim the message-account rent of a CCTP rebalance (for a backend cron job; safe to call repeatedly)
 * Flow: account missing -> already reclaimed; attestation pending -> wait; window not expired -> wait; otherwise send the reclaim tx.
 * Suggestion: after persisting RebalanceCctpEvent, call this once a day for records that arrived but are not reclaimed yet.
 */
export async function reclaimCctpEventAccount(
  connection: Connection,
  payee: Keypair,
  txSignature: string,
  eventAccount: PublicKey,
  opts: { testnet?: boolean; fetchImpl?: typeof fetch } = {}
): Promise<ReclaimResult> {
  const info = await connection.getAccountInfo(eventAccount, "confirmed");
  if (!info) return { status: "already_closed" };
  const st = await fetchCctpAttestation(txSignature, opts);
  if (!st?.message || !st.attestation) return { status: "attestation_pending", cctpStatus: st?.status ?? null };
  const tx = new Transaction().add(reclaimCctpEventAccountIx(payee.publicKey, eventAccount, st.attestation, st.message));
  try {
    const signature = await sendAndConfirmTransaction(connection, tx, [payee], { commitment: "confirmed" });
    return { status: "reclaimed", signature, lamports: info.lamports };
  } catch (e: any) {
    const text = String(e?.message ?? e) + JSON.stringify(e?.logs ?? []);
    if (text.includes("EventAccountWindowNotExpired")) return { status: "window_not_expired" };
    throw e;
  }
}

