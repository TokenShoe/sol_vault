/** EVM address (0x + 40 hex chars) -> CCTP mint_recipient (left-padded with 12 zero bytes, 32 bytes total) */
export function evmAddressToBytes32(addr: string): PublicKey {
  const hex = addr.toLowerCase().replace(/^0x/, "");
  if (!/^[0-9a-f]{40}$/.test(hex)) throw new Error(`invalid EVM address: ${addr}`);
  return new PublicKey(Buffer.concat([Buffer.alloc(12), Buffer.from(hex, "hex")]));
}

/** CCTP 32-byte address -> EVM address (last 20 bytes). Used to display mint_recipient from events / routes as 0x... */
export function bytes32ToEvmAddress(b: PublicKey): string {
  return "0x" + Buffer.from(b.toBytes()).subarray(12).toString("hex");
}

