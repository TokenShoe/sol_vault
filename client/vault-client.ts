/** Must be checked before the feepayer signs: only ComputeBudget + this program's instructions, and the feepayer must not appear in any instruction accounts */
export function assertSafeForFeePayer(tx: Transaction, feePayer: PublicKey) {
  for (const ix of tx.instructions) {
    if (!ix.programId.equals(ComputeBudgetProgram.programId) && !ix.programId.equals(PROGRAM_ID)) {
      throw new Error(`forbidden program ${ix.programId.toBase58()}`);
    }
    if (ix.keys.some((k) => k.pubkey.equals(feePayer))) throw new Error("feePayer used inside instruction");
  }
}

