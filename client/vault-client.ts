export interface DepositParams {
  user: PublicKey;
  feePayer: PublicKey;
  mint: PublicKey;
  orderId: number[];
  amount: bigint | number; // fee included, USDC has 6 decimals
  fee: bigint | number;
  destChainId: number;
  recipient: string; // receiving address on the destination chain
  targetToken: string; // meme contract on the destination chain
  minAmountOut?: bigint | number;
}

/** Backend builds -> feePayer.partialSign -> user wallet signs -> send */
export async function buildDepositTx(program: Program<CrossVault>, p: DepositParams): Promise<Transaction> {
  const ix = await program.methods
    .depositForSwap({
      orderId: p.orderId,
      amount: bn(p.amount),
      fee: bn(p.fee),
      destChainId: bn(p.destChainId),
      recipient: p.recipient,
      targetToken: p.targetToken,
      minAmountOut: bn(p.minAmountOut ?? 0),
    })
    .accountsPartial({
      user: p.user,
      mint: p.mint,
      pool: poolPda(p.mint),
      vault: vaultAddress(p.mint),
      userToken: getAssociatedTokenAddressSync(p.mint, p.user),
      tokenProgram: TOKEN_PROGRAM_ID,
    })
    .instruction();
  const { blockhash, lastValidBlockHeight } = await program.provider.connection.getLatestBlockhash();
  return new Transaction({ feePayer: p.feePayer, blockhash, lastValidBlockHeight }).add(
    ComputeBudgetProgram.setComputeUnitLimit({ units: 60_000 }),
    ix
  );
}

// ------------------------------ V2: encrypted-params deposit ------------------------------
/** V2 encrypted destination params (JSON-serialized then encrypted; ciphertext must be <= 256 bytes) */
export interface SwapParams {
  destChainId: number;
  recipient: string; // receiving address on the destination chain
  targetToken: string; // meme contract on the destination chain
  minAmountOut?: string; // decimal string
}

/** Platform encryption key pair (x25519). Keep secretKey on the backend only; ship publicKey to the frontend */
export const generateEncryptionKeyPair = () => nacl.box.keyPair();

/**
 * Frontend encryption: a fresh ephemeral key pair per call, output = [ephemeral pubkey 32][nonce 24][ciphertext]
 * Only the backend holding the platform secretKey can decrypt
 */
export function encryptSwapParams(params: SwapParams, platformPublicKey: Uint8Array): Buffer {
  const eph = nacl.box.keyPair();
  const nonce = nacl.randomBytes(nacl.box.nonceLength);
  const msg = Buffer.from(
    JSON.stringify({ c: params.destChainId, r: params.recipient, t: params.targetToken, m: params.minAmountOut ?? "0" })
  );
  const box = nacl.box(msg, nonce, platformPublicKey, eph.secretKey);
  const out = Buffer.concat([Buffer.from(eph.publicKey), Buffer.from(nonce), Buffer.from(box)]);
  if (out.length > 256) throw new Error(`encrypted params too long: ${out.length} > 256`);
  return out;
}

/** Backend decrypts DepositForSwapV2Event.encryptedParams */
export function decryptSwapParams(data: Uint8Array, platformSecretKey: Uint8Array): SwapParams {
  const buf = Buffer.from(data);
  const ephPub = buf.subarray(0, 32);
  const nonce = buf.subarray(32, 56);
  const opened = nacl.box.open(buf.subarray(56), nonce, ephPub, platformSecretKey);
  if (!opened) throw new Error("decrypt failed");
  const j = JSON.parse(Buffer.from(opened).toString());
  return { destChainId: j.c, recipient: j.r, targetToken: j.t, minAmountOut: j.m };
}

