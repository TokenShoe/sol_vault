/** Status of a token pool: balance / watermark / withdrawable (excess) / to top up (deficit) */
export async function getPoolStatus(program: Program<CrossVault>, mint: PublicKey) {
  const pool = await program.account.pool.fetch(poolPda(mint));
  const bal = await program.provider.connection.getTokenAccountBalance(pool.vault);
  const balance = BigInt(bal.value.amount);
  const watermark = BigInt(pool.watermark.toString());
  // Relay staging account (Relay refunds land here); absent until the first rebalance_relay
  const staging = await program.provider.connection.getTokenAccountBalance(relayStagingAddress(mint)).catch(() => null);
  return {
    pool,
    balance,
    relayStagingBalance: staging ? BigInt(staging.value.amount) : 0n,
    watermark,
    excess: balance > watermark ? balance - watermark : 0n,
    deficit: balance < watermark ? watermark - balance : 0n,
  };
}

// ------------------------------ events ------------------------------
export interface ParsedEvent {
  name: string;
  data: any;
  signature: string;
  slot: number;
}

/** Parse this program's emit_cpi events from a transaction */
export async function parseEventsFromTx(
  program: Program<CrossVault>,
  signature: string,
  commitment: Finality = "confirmed"
): Promise<ParsedEvent[]> {
  const tx = await program.provider.connection.getTransaction(signature, { commitment, maxSupportedTransactionVersion: 0 });
  if (!tx || tx.meta?.err) return [];
  const keys = tx.transaction.message.getAccountKeys({ accountKeysFromLookups: tx.meta?.loadedAddresses });
  const out: ParsedEvent[] = [];
  for (const group of tx.meta?.innerInstructions ?? []) {
    for (const ix of group.instructions) {
      if (!keys.get(ix.programIdIndex)?.equals(PROGRAM_ID)) continue;
      const raw = Buffer.from(bs58.decode(ix.data));
      if (raw.length < 16 || !raw.subarray(0, 8).equals(EVENT_IX_TAG)) continue;
      const ev = program.coder.events.decode(raw.subarray(8).toString("base64"));
      if (ev) out.push({ name: ev.name, data: ev.data, signature, slot: tx.slot });
    }
  }
  return out;
}

/** Real-time websocket listener; in production also run backfillEvents periodically and process idempotently by order_id */
export function listenEvents(
  program: Program<CrossVault>,
  onEvent: (e: ParsedEvent) => void | Promise<void>,
  onError: (err: unknown) => void = console.error
): number {
  return program.provider.connection.onLogs(
    PROGRAM_ID,
    async (logs) => {
      if (logs.err) return;
      try {
        for (let i = 0; i < 5; i++) {
          const evs = await parseEventsFromTx(program, logs.signature);
          if (evs.length) {
            for (const e of evs) await onEvent(e);
            return;
          }
          await new Promise((r) => setTimeout(r, 800));
        }
      } catch (err) {
        onError(err);
      }
    },
    "confirmed"
  );
}

/** Backfill: fetch transactions after untilSignature and parse their events (chronological order) */
export async function backfillEvents(program: Program<CrossVault>, untilSignature?: string, limit = 1000) {
  const sigs = await program.provider.connection.getSignaturesForAddress(PROGRAM_ID, { until: untilSignature, limit }, "confirmed");
  const out: ParsedEvent[] = [];
  for (const s of sigs.reverse()) {
    if (!s.err) out.push(...(await parseEventsFromTx(program, s.signature)));
  }
  return out;
}
