/** Build one debit instruction: transfer amount from the vault to destination (any token account of the mint, not the vault) */
export async function debitIx(
  program: Program<CrossVault>,
  operator: PublicKey,
  mint: PublicKey,
  destination: PublicKey,
  id: number[],
  amount: bigint | number
): Promise<TransactionInstruction> {
  return program.methods
    .debit(id, bn(amount))
    .accountsPartial({
      operator,
      mint,
      pool: poolPda(mint),
      vault: vaultAddress(mint),
      destination,
      tokenProgram: TOKEN_PROGRAM_ID,
    })
    .instruction();
}

/**
 * Payout after a user sells (mirrors pump: two AdminDebit in one transaction)
 *   [optional] create the user's token account (skipped if it exists, rent paid by operator)
 *   debit(order_id, amount) -> user's token account
 *   debit(order_id, fee)    -> fee wallet's token account (omitted when fee = 0)
 * All in one transaction: either everything succeeds or everything fails.
 */
export async function payoutToUser(
  program: Program<CrossVault>,
  operator: Keypair,
  mint: PublicKey,
  user: PublicKey,
  id: number[],
  amount: bigint | number,
  fee: bigint | number = 0,
  feeWallet?: PublicKey
): Promise<string> {
  const userAta = getAssociatedTokenAddressSync(mint, user, true);
  const ixs: TransactionInstruction[] = [
    ComputeBudgetProgram.setComputeUnitLimit({ units: 120_000 }),
    createAssociatedTokenAccountIdempotentInstruction(operator.publicKey, userAta, user, mint),
    await debitIx(program, operator.publicKey, mint, userAta, id, amount),
  ];
  if (BigInt(fee) > 0n) {
    if (!feeWallet) throw new Error("fee > 0 but feeWallet not provided");
    const feeAta = getAssociatedTokenAddressSync(mint, feeWallet, true);
    ixs.push(await debitIx(program, operator.publicKey, mint, feeAta, id, fee));
  }
  const tx = new Transaction().add(...ixs);
  return sendAndConfirmTransaction(program.provider.connection, tx, [operator], { commitment: "confirmed" });
}

